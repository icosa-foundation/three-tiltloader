import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const [ inputFile, outputFile ] = process.argv.slice( 2 );
if ( ! inputFile || ! outputFile ) {
	throw new Error(
		'Usage: node scripts/generate-open-brush-defaults.mjs <brush-assets.json> <output.ts>'
	);
}

const document = JSON.parse( await readFile( inputFile, 'utf8' ) );
if ( ! document.brushes || typeof document.brushes !== 'object' ) {
	throw new Error( 'Input must contain a brushes object.' );
}

const geometryOverrides = {
	'f0a2298a-be80-432c-9fee-a86dcc06f4f9': {
		// Open Brush BrushDescriptor.m_BackIsInvisible for SingleSided.
		backIsInvisible: true
	}
};

function resolveFamily( brush ) {
	if ( brush.generatorClass === 'SquareBrush' ) return 'tube';
	if ( brush.generatorClass === 'Square3DPrintBrush' ) return 'print3d';
	if ( brush.generatorClass === 'ConcaveHullBrush' ) return 'concave-hull';
	return brush.generatorFamily ?? 'unsupported';
}

const defaults = {};
for ( const guid of Object.keys( document.brushes ).sort() ) {
	const brush = document.brushes[ guid ];
	const geometry = brush.geometry ?? {};
	const {
		pressureSizeRange,
		pressureOpacityRange,
		...geometryParams
	} = geometry;
	Object.assign( geometryParams, geometryOverrides[ guid ] );
	defaults[ guid.toLowerCase() ] = {
		family: resolveFamily( brush ),
		generatorClass: brush.generatorClass,
		pressureSizeRange,
		pressureOpacityRange,
		geometryParams
	};
}

const header = `// Generated by scripts/generate-open-brush-defaults.mjs.\n` +
	`// Geometry-affecting Open Brush defaults are package data; callers may override them per generation.\n` +
	`import type { BrushGeometryDefaults } from "./brush-defaults.js";\n\n`;
const source = `${header}export const OPEN_BRUSH_GEOMETRY_DEFAULTS = ${JSON.stringify(
	defaults,
	null,
	2
)} as const satisfies Readonly<Record<string, BrushGeometryDefaults>>;\n`;

await writeFile( outputFile, source, 'utf8' );
process.stdout.write( `Wrote ${path.relative( process.cwd(), outputFile )}\n` );
